#!/usr/bin/env python3
"""Register the graph with an OpenViking server, so its retrieval covers the record.

    cairn openviking status            # is `ov` here, is a server up, what would be pushed
    cairn openviking push              # dry run: print the `ov` commands
    cairn openviking push --apply      # run them

OpenViking (github.com/volcengine/OpenViking) is a context database for agents:
a `viking://` filesystem of resources, memories and skills, with semantic
retrieval and session-history summarisation, served by a process that needs an
embedding model and a VLM. Its Claude Code plugin injects relevant memories
before every prompt and commits each session's turns for memory extraction.

Cairn is the research-specific layer, and the two meet at exactly one seam:

- **Cairn -> OpenViking: the graph is a resource.** `nodes/` and the two derived
  files that read it back (`build/graph.md`, `build/report.md`) are registered
  under `viking://resources/cairn/<graph>/`. OpenViking then does what it does —
  abstracts, overviews, embeddings — and "did we already try this?" gets
  answered by its recall as well as by `cairn standup`. `--to` is used rather
  than `--parent` because re-adding to a `--to` target refreshes it in place;
  `--parent` would mint `nodes_1`, `nodes_2`, … on every push.
- **OpenViking -> Cairn: memories are capture, never nodes.** What OpenViking
  extracts from a session is an unreviewed summary. It belongs in `inbox/` for
  triage, exactly like any other unprompted writing (design decision 7), and
  nothing here writes a node from it. That direction is a `cairn capture` away
  and is left to the agent, which can read `viking://~/memories/` through the
  plugin's own tools.

What stays refused, and why: no import of OpenViking's Python package (AGPLv3,
and Cairn's one dependency is PyYAML); no server in Cairn's own path — every
command here works with `ov` absent, by saying so; no write of OpenViking state
into `nodes/`. The graph format is identical with or without it.

Not yet verified against a live server. The commands follow the documented CLI
(`ov add-resource <path> --to <uri> --reason ...`); the dry run exists so a
wrong flag costs a read, not a write.
"""

from __future__ import annotations

import argparse
import os
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

TOOL_ROOT = Path(__file__).resolve().parent.parent
GRAPH_ROOT = Path(os.environ.get("CAIRN_ROOT") or TOOL_ROOT).expanduser().resolve()

#: What gets registered, and in what order. nodes/ first because it is the
#: record; the two build/ files second because they are the record read back,
#: and the cheapest thing for a retriever to land on.
RESOURCES = (
    ("nodes", "Cairn research graph: one markdown node per experiment, dead end, "
              "open thread, task or milestone. Frontmatter is the schema; "
              "`status: dead` means refuted, with the reason in history."),
    ("build/graph.md", "Cairn: the graph as Mermaid, regenerated by `cairn build`."),
    ("build/report.md", "Cairn: where to start, cross-project connections, and coverage — "
                        "how much to trust a gap. Regenerated by `cairn build`."),
)


def target_prefix(graph: Path) -> str:
    return f"viking://resources/cairn/{graph.name}"


def ov() -> str | None:
    return shutil.which("ov")


def plan(graph: Path) -> list[tuple[list[str], str]]:
    """[(command, why-skipped-or-empty)] for each resource."""
    out = []
    prefix = target_prefix(graph)
    for rel, reason in RESOURCES:
        src = graph / rel
        cmd = ["ov", "add-resource", str(src), "--to", f"{prefix}/{rel}", "--reason", reason]
        skip = ""
        if not src.exists():
            skip = ("run `cairn build` first" if rel.startswith("build/")
                    else f"{src} does not exist")
        elif rel == "nodes" and not any(src.glob("*.md")):
            skip = "no nodes yet — nothing to register"
        out.append((cmd, skip))
    return out


def status(graph: Path) -> int:
    binary = ov()
    print(f"cairn openviking — graph {graph}")
    print(f"  target {target_prefix(graph)}/")
    if not binary:
        print("  ov     not on PATH — OpenViking is optional; Cairn is complete without it.")
        print("         install: https://github.com/volcengine/OpenViking  (needs a running server)")
        return 0
    print(f"  ov     {binary}")
    try:
        done = subprocess.run([binary, "status"], capture_output=True, text=True, timeout=20)
        first = (done.stdout or done.stderr).strip().splitlines()
        print(f"  server {'reachable' if done.returncode == 0 else 'not reachable'}"
              + (f" — {first[0]}" if first else ""))
    except (OSError, subprocess.SubprocessError) as exc:
        print(f"  server could not run `ov status`: {exc}")
    print()
    for cmd, skip in plan(graph):
        print(f"  {'skip ' if skip else 'would'} {cmd[2]} -> {cmd[4]}" + (f"  ({skip})" if skip else ""))
    print("\n  `cairn openviking push --apply` registers them; without --apply it only prints.")
    return 0


def push(graph: Path, apply: bool) -> int:
    binary = ov()
    if not binary:
        print("cairn openviking: `ov` is not on PATH. Nothing to push to — and nothing lost:",
              file=sys.stderr)
        print("  OpenViking is optional. Install it and start its server, or skip this.",
              file=sys.stderr)
        return 1
    print(f"cairn openviking push — {graph} -> {target_prefix(graph)}/"
          + ("" if apply else "   (dry run)"))
    failures = 0
    for cmd, skip in plan(graph):
        shown = " ".join(_quote(c) for c in cmd)
        if skip:
            print(f"  skip  {shown}\n        {skip}")
            continue
        print(f"  {'run ' if apply else 'would'}  {shown}")
        if not apply:
            continue
        try:
            done = subprocess.run([binary, *cmd[1:]], capture_output=True, text=True, timeout=600)
        except (OSError, subprocess.SubprocessError) as exc:
            print(f"        failed: {exc}")
            failures += 1
            continue
        tail = (done.stdout + done.stderr).strip().splitlines()
        for line in tail[-3:]:
            print(f"        {line}")
        if done.returncode != 0:
            failures += 1
    if not apply:
        print("\nDry run. Nothing sent. Re-run with --apply.")
    elif failures:
        print(f"\n{failures} resource(s) failed — the graph itself is unaffected.")
        return 1
    else:
        print("\nRegistered. OpenViking processes resources in the background; `ov task status`")
        print("says when a summary is ready, and `ov find \"<question>\"` searches it.")
    return 0


def _quote(s: str) -> str:
    return shlex.quote(s)


def main() -> int:
    p = argparse.ArgumentParser(
        prog="cairn openviking",
        description="Register the research graph with an OpenViking server (optional).")
    p.add_argument("action", nargs="?", choices=("status", "push"), default="status")
    p.add_argument("--apply", action="store_true", help="actually run the ov commands")
    args = p.parse_args()

    if not (GRAPH_ROOT / "nodes").is_dir():
        print(f"cairn openviking: no graph at {GRAPH_ROOT} — export CAIRN_ROOT or run cairn init",
              file=sys.stderr)
        return 2
    if args.action == "push":
        return push(GRAPH_ROOT, args.apply)
    return status(GRAPH_ROOT)


if __name__ == "__main__":
    sys.exit(main())
